def grid(rows):
    assert len(rows) in (8, 16), len(rows)
    return [[int(ch, 16) for ch in row] for row in rows]

def tile_words(g, ox, oy):
    """8x8 subtile at offset (ox,oy) of a 16x16 (or the 8x8 itself) -> 8 u32 words."""
    words = []
    for y in range(8):
        w = 0
        for bx in range(4):
            byte = 0
            for px in range(2):
                byte |= g[oy + y][ox + bx * 2 + px] << (4 * px)
            w |= byte << (8 * bx)
        words.append(w)
    return words

def emit_tiles(name, grids):
    out = [f"static const unsigned int {name}[{len(grids) * 4}][8] = {{"]
    for g in grids:
        for ox, oy in ((0, 0), (8, 0), (0, 8), (8, 8)):
            out.append("    {" + ",".join(f"0x{w:08X}" for w in tile_words(g, ox, oy)) + "},")
    out.append("};")
    return "\n".join(out)

def base_floor(seed):
    # dressed stone slabs: deep grout, per-slab tone, top-left bevel light, speckle + wear
    g = [[2] * 16 for _ in range(16)]
    for y in range(16):
        for x in range(16):
            sx, sy = x // 8, y // 8
            tone = 3 if (sx * 3 + sy * 5 + seed) % 3 == 0 else 2
            g[y][x] = tone
            if x % 8 == 0 or y % 8 == 0: g[y][x] = 4                      # grout shadow
            elif x % 8 == 1 or y % 8 == 1: g[y][x] = 3 if tone == 2 else tone  # bevel catch-light
            h = (x * 31 + y * 17 + seed * 13) % 23
            if h == 0: g[y][x] = 1                                        # pitted stone
            elif h == 7: g[y][x] = 3 if tone == 2 else 2                  # worn patch
            elif h == 13 and y > 11: g[y][x] = 0xE                         # moss creeping at the base
    return g

def wall_grid(art=False):
    # coursed brickwork: offset joints, per-brick tone, lit crown, shadowed foot, cracks
    g = [[5] * 16 for _ in range(16)]
    for y in range(16):
        for x in range(16):
            course = y // 4
            off = 4 if course % 2 else 0
            if y % 4 == 3: g[y][x] = 7                                    # mortar line
            elif (x + off) % 8 == 7: g[y][x] = 7                          # perpend joint
            else:
                g[y][x] = 6 if (x // 4 + course * 2) % 3 == 0 else 5      # brick tone variation
                if (x * 13 + y * 29) % 31 == 0: g[y][x] = 4               # spalled brick
            if y == 0: g[y][x] = 6                                        # crown catches the light
            if y == 1 and x % 3: g[y][x] = 6
            if y == 15: g[y][x] = 4                                       # foot in shadow
            if y == 14 and (x * 7 + 3) % 5 == 0: g[y][x] = 0xE            # damp moss at the base
    if (5, 6) and True:
        for (cx, cy) in ((12, 5), (13, 6), (13, 7)): g[cy][cx] = 7        # a hairline crack
    if art:  # portrait: gilt frame with inner shadow, a pale haunted face
        for y in range(3, 13):
            for x in range(5, 11):
                g[y][x] = 0xC if x in (5, 10) or y in (3, 12) else 8
        for y in range(4, 12):
            for x in range(6, 10): g[y][x] = 9 if x == 6 or y == 4 else 8  # canvas shading
        for y in range(5, 9):
            for x in range(7, 9): g[y][x] = 0xD                            # the face (bone pale)
        g[6][7] = g[6][8] = 1                                              # hollow eyes
        g[10][7] = g[10][8] = 0xD                                          # high collar
        g[4][5] = g[3][10] = 0xF                                            # gilt glints
    return g

def carpet_grid():
    # woven runner: deep red field, knotted border, gold diamond motif, worn pile
    g = base_floor(3)
    for y in range(16):
        for x in range(16):
            if x in (0, 15) or y in (0, 15): g[y][x] = 0xB
            elif x in (1, 14) or y in (1, 14): g[y][x] = 0xC if (x + y) % 2 else 0xA
            else:
                g[y][x] = 0xA
                d = abs(x - 7.5) + abs(y - 7.5)
                if d in (2.5, 3.5): g[y][x] = 0xC                     # gold diamond ring
                elif d < 2.5: g[y][x] = 0xB                          # dark medallion heart
                elif (x + y) % 6 == 0 or (x - y) % 6 == 0: g[y][x] = 0xB
                if (x * 11 + y * 7) % 29 == 0: g[y][x] = 8            # threadbare patch
    g[7][7] = g[7][8] = g[8][7] = g[8][8] = 0xF
    return g

def cracked_grid():
    g = base_floor(9)
    for x, y in ((3, 2), (4, 3), (4, 4), (5, 5), (6, 6), (6, 7), (7, 8), (11, 10), (10, 11), (10, 12), (9, 13)):
        g[y][x] = 4
    return g

def pillar_grid():
    g = wall_grid()
    for y in range(16):
        for x in range(16):
            if 6 <= x <= 9: g[y][x] = 5
            if x in (5, 10): g[y][x] = 6
            if y in (2, 3, 12, 13) and 5 <= x <= 10: g[y][x] = 0xC
    return g


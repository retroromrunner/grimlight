def _radial(cx, cy, r_in, r_mid, r_out):
    g = [[0] * 16 for _ in range(16)]
    for y in range(16):
        for x in range(16):
            d = ((x - cx) ** 2 + (y - cy) ** 2) ** 0.5
            if d < r_in: g[y][x] = 0xF
            elif d < r_mid: g[y][x] = 0xF if (x + y) % 2 else 0xB
            elif d < r_out: g[y][x] = 0xB if (x + y) % 2 else 0
    return g

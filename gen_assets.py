def font_tiles():
    tiles = []
    for ch in FONT_CHARS:
        g = [[1 if c == '#' else 0 for c in row] for row in _G[ch]]
        tiles.append(g)
    out = []
    for g in tiles:
        words = []
        for y in range(8):
            w = 0
            for bx in range(4):
                byte = 0
                for px in range(2):
                    byte |= g[y][bx * 2 + px] << (4 * px)
                w |= byte << (8 * bx)
            words.append(w)
        out.append(words)
    return out

